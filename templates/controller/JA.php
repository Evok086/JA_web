<div class="p-3">
    <h1 class="mb-4 m-4 text-balance text-3xl font-semibold tracking-tight">Qu'est-ce que la JA ?</h1>

    <p class="m-4">
        La <strong>Jeunesse Adventiste (JA)</strong> est un mouvement qui accompagne les jeunes dans
        leur parcours personnel et spirituel. Elle cherche à favoriser une rencontre
        <em>authentique, directe et simple</em> avec Jésus-Christ — une rencontre qui éclaire,
        transforme et s'inscrit dans la vie quotidienne.
    </p>

    <article class="m-4 space-y-4">
        <section>
            <h2 class="text-lg font-medium mb-2">Foi incarnée dans le quotidien</h2>
            <p>
                La JA aide les jeunes à relier leur spiritualité à leurs choix, leurs relations, leurs études
                et leurs projets. La foi devient alors une pratique vécue au quotidien : discernement,
                cohérence et espérance guident les actes de chaque jour.
            </p>
        </section>

        <section>
            <h2 class="text-lg font-medium mb-2">Former des citoyens engagés</h2>
            <p>
                Convaincue que la foi se traduit par l’action, la JA encourage les jeunes à s’investir pour
                la justice, la solidarité et le bien commun. Elle forme des citoyens responsables, capables
                d’apporter une contribution positive à la société.
            </p>
        </section>

        <section>
            <h2 class="text-lg font-medium mb-2">Dynamiser la vie d’église</h2>
            <p>
                La JA se vit au sein de la communauté. Elle invite chaque jeune à s’impliquer, à exprimer
                ses talents et à prendre des responsabilités pour rendre l’église plus vivante,
                accueillante et missionnaire.
            </p>
        </section>

        <section>
            <h2 class="text-lg font-medium mb-2">Développement intégral de la personne</h2>
            <p>
                La JA promeut un développement global qui respecte toutes les dimensions humaines :
            </p>
            <ul class="list-disc pl-7 flex flex-col gap-2 mt-2">
                <li><strong>Physique :</strong> activités sportives, plein air et promotion d’un mode de vie sain.</li>
                <li><strong>Psychologique :</strong> accompagnement, confiance en soi et résilience.</li>
                <li><strong>Intellectuel :</strong> apprentissage, créativité et pensée critique.</li>
                <li><strong>Spirituel :</strong> étude biblique, prière et vie de service.</li>
            </ul>
            <p class="mt-2">
                L’objectif est d’aider chaque jeune à découvrir ses dons, à les développer et à les mettre au service des autres.
            </p>
        </section>

        <section>
            <h2 class="text-lg font-medium mb-2">Conscience écologique et responsabilité</h2>
            <p>
                Sensible aux défis environnementaux, la JA sensibilise les jeunes à la préservation de la
                création. Prendre soin de la nature, c’est aussi protéger l’humanité : un engagement écologique
                fait partie intégrante de la mission.
            </p>
        </section>

        <section>
            <h2 class="text-lg font-medium mb-2">Pédagogie active et respectueuse</h2>
            <p>
                Pour atteindre ces objectifs, la JA privilégie des méthodes participatives et concrètes.
                Les jeunes sont acteurs : ils expérimentent, créent, servent et apprennent dans un cadre
                bienveillant qui respecte le rythme de chacun.
            </p>
            <ul class="list-disc pl-7 flex flex-col gap-2 mt-2">
                <li>Ateliers pratiques, projets solidaires et actions citoyennes.</li>
                <li>Camps, temps spirituels et sessions de formation.</li>
                <li>Espaces d’expression pour encourager l’initiative et la créativité.</li>
            </ul>
        </section>
    </article>

    <p class="m-4">
        <strong>En résumé :</strong> la Jeunesse Adventiste est une communauté vivante qui accompagne
        les jeunes sur le plan spirituel, personnel et citoyen. Elle vise à former des personnes
        épanouies, responsables et engagées — prêtes à transformer leur église, leur société et le monde.
    </p>

